#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);

const SETS = {};
for (const name of ["tabler", "simple-icons"]) {
  SETS[name] = JSON.parse(
    fs.readFileSync(require.resolve(`@iconify-json/${name}/icons.json`), "utf8"),
  );
}

// Keep the existing DSL names stable while resolving them to Iconify icons.
const ALIASES = {
  api: "tabler:api",
  bucket: "tabler:bucket",
  ceph: "simple-icons:ceph",
  cloud: "tabler:cloud",
  cog: "tabler:settings",
  container: "tabler:box",
  database: "tabler:database",
  disk: "tabler:device-floppy",
  gateway: "tabler:router",
  globe: "tabler:world",
  kubernetes: "simple-icons:kubernetes",
  linux: "simple-icons:linux",
  loadbalancer: "tabler:load-balancer",
  lock: "tabler:lock",
  monitor: "tabler:device-desktop",
  network: "tabler:network",
  openstack: "simple-icons:openstack",
  queue: "tabler:stack-2",
  server: "tabler:server",
  storage: "tabler:archive",
  switch: "tabler:topology-star-3",
  user: "tabler:user",
  vm: "tabler:device-desktop-analytics",
};

const DEFAULTS = ["server", "switch", "vm"];
const OUTPUT = path.join(root, "src", "diagram", "icons_generated.rs");

function getIcon(set, name) {
  const data = SETS[set];
  if (data.icons[name]) return data.icons[name];
  const alias = data.aliases?.[name];
  if (!alias) return null;
  const parent = data.icons[alias.parent];
  return parent ? { ...parent, ...alias } : null;
}

function resolveIcon(name) {
  if (name.includes(":")) {
    const [set, icon] = name.split(":", 2);
    if (!SETS[set]) {
      throw new Error(`unknown icon set "${set}" in "${name}"`);
    }
    const data = getIcon(set, icon);
    if (!data) throw new Error(`icon "${icon}" not found in ${set}`);
    return { set, data };
  }

  if (ALIASES[name]) {
    const [set, icon] = ALIASES[name].split(":", 2);
    const data = getIcon(set, icon);
    if (!data) throw new Error(`alias "${name}" points to missing ${ALIASES[name]}`);
    return { set, data };
  }

  for (const set of ["tabler", "simple-icons"]) {
    const data = getIcon(set, name);
    if (data) return { set, data };
  }
  throw new Error(`icon "${name}" not found in Tabler or Simple Icons`);
}

function markup({ set, data }) {
  const width = Number(data.width ?? SETS[set].width ?? 24);
  const height = Number(data.height ?? SETS[set].height ?? 24);
  if (width !== 24 || height !== 24 || data.left || data.top) {
    throw new Error(`icon must use a 24x24 viewBox, got ${width}x${height}`);
  }
  const body = data.body;
  return set === "simple-icons" ? `<g class="dg-icon-filled">${body}</g>` : body;
}

function rustRaw(value) {
  let hashes = "#";
  while (value.includes(`"${hashes}`)) hashes += "#";
  return `r${hashes}"${value}"${hashes}`;
}

const names = new Set(DEFAULTS);
const diagramDir = path.join(root, "diagrams");
for (const file of fs.readdirSync(diagramDir).filter((name) => /\.ya?ml$/i.test(name))) {
  const text = fs.readFileSync(path.join(diagramDir, file), "utf8");
  for (const match of text.matchAll(/^\s*icon:\s*["']?([^"'\s#]+)/gm)) {
    names.add(match[1]);
  }
}

const sorted = [...names].sort();
const lines = [
  "// @generated by scripts/icons.mjs from Iconify. Do not edit by hand.",
  "// Run `npm run icons` after adding or changing an `icon:` value.",
  "",
  `pub const ICON_NAMES: &[&str] = &[${sorted.map((name) => JSON.stringify(name)).join(", ")}];`,
  "",
  "pub fn exists(name: &str) -> bool {",
  "    ICON_NAMES.contains(&name)",
  "}",
  "",
  "pub fn markup(name: &str) -> Option<&'static str> {",
  "    Some(match name {",
];
for (const name of sorted) {
  const icon = resolveIcon(name);
  lines.push(`        ${JSON.stringify(name)} => ${rustRaw(markup(icon))},`);
}
lines.push("        _ => return None,", "    })", "}", "");
const next = lines.join("\n");

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : "";
  const normalize = (value) => value.replace(/\s+/g, "");
  if (normalize(current) !== normalize(next)) {
    console.error("icons_generated.rs is out of date; run `npm run icons`");
    process.exit(1);
  }
  console.log(`icons: ${sorted.length} up to date`);
} else {
  fs.writeFileSync(OUTPUT, next);
  console.log(`icons: ${sorted.length} generated from Iconify`);
}
